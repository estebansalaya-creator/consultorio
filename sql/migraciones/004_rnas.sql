-- Completa el código de las obras sociales ya cargadas cuando el nombre coincide con un solo agente
-- (por sigla, o porque la denominación oficial empieza con el nombre). PAMI se reconoce aparte.
UPDATE obras_sociales o
  JOIN (SELECT o2.id, MIN(a.rnas) AS rnas, COUNT(*) AS n
          FROM obras_sociales o2
          JOIN agentes_seguro a ON a.sigla = o2.nombre OR a.denominacion LIKE CONCAT(o2.nombre, ' %')
         GROUP BY o2.id) m ON m.id = o.id AND m.n = 1
   SET o.rnas = m.rnas
 WHERE o.rnas IS NULL;
